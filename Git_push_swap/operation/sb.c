#include "push_swap.h"
#include "operation.h"

void	sb(t_stack **stack, t_ops *ops_count)
{
	t_stack	*first;
	t_stack	*second;

	if (!*stack || !(*stack)->next)
		return ;
	first = *stack;
	second = (*stack)->next;
	first->next = second->next;
	second->next = first;
	*stack = second;
	ft_putstr_fd("sb\n", 1);
	ops_count->sb++;
	ops_count->total++;
}
